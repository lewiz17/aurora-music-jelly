export type TranslateFn = (key: TranslationKey) => string

export const createTranslator =
    (language: Language): TranslateFn =>
    key => {
        const table = translations[language] || translations.es
        return (table as Record<string, string>)[key] ?? (translations.en as Record<string, string>)[key] ?? key
    }

interface I18nContextValue {
    language: Language
    setLanguage: (language: Language) => void
    t: TranslateFn
}

export const I18nContext = createContext<I18nContextValue>({
    language: 'es',
    setLanguage: () => {},
    t: createTranslator('es'),
})

export const useI18n = () => useContext(I18nContext)
export const useT = () => useContext(I18nContext).t
