export const getTheme = (id: string, themes: ThemeDefinition[] = THEMES) =>
    themes.find(theme => theme.id === id) || themes[0] || THEMES[0]

/** Writes the variables for the active appearance onto :root. */
export const applyThemeVars = (dark: Record<string, string>, light: Record<string, string>) => {
    const root = document.documentElement
    const isDark = root.classList.contains('dark')
    const vars = isDark ? dark : light
    for (const [key, value] of Object.entries(vars)) {
        root.style.setProperty(key, value)
    }
}

export const applyThemeById = (id: string, themes: ThemeDefinition[] = THEMES) => {
    const theme = getTheme(id, themes)
    applyThemeVars(theme.dark, theme.light)
}


/**
 * Derived variables. Turns a theme's brand color into tinted backgrounds so that
 * surfaces (cards, dropdowns, active rows) follow the gradient instead of the
 * original lilac palette.
 */
export const withDerivedVars = (vars: Record<string, string>): Record<string, string> => {
    const brand = vars['--brand-color'] || '#7b5cff'
    return {
        ...vars,
        '--brand-tint-04': hexToRgba(brand, 0.04),
        '--brand-tint-06': hexToRgba(brand, 0.06),
        '--brand-tint-08': hexToRgba(brand, 0.08),
        '--brand-tint-10': hexToRgba(brand, 0.1),
        '--brand-tint-12': hexToRgba(brand, 0.12),
        '--brand-tint-16': hexToRgba(brand, 0.16),
        '--brand-tint-22': hexToRgba(brand, 0.22),
        '--brand-tint-35': hexToRgba(brand, 0.35),
        '--bg-color-dimmer': hexToRgba(brand, 0.45),
        '--bg-tint-50': hexToRgba(brand, 0.5),
        '--app-brand-gradient': vars['--app-gradient'] || `linear-gradient(135deg, ${brand} 0%, ${brand} 100%)`,
    }
}

const hexToRgba = (hex: string, alpha: number) => {
    const clean = hex.replace('#', '')
    if (clean.length !== 6) return `rgba(123, 92, 255, ${alpha})`
    const r = parseInt(clean.slice(0, 2), 16)
    const g = parseInt(clean.slice(2, 4), 16)
    const b = parseInt(clean.slice(4, 6), 16)
    return `rgba(${r}, ${g}, ${b}, ${alpha})`
}
